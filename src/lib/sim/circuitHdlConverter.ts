export function parseHardwareDescriptionLanguage(source: string): ParseResult {
  const trimmed = source.trim();
  // Auto-detect: VHDL keywords vs Verilog
  const isVhdl = /^\s*library\s+ieee/i.test(trimmed) || /entity\s+\w+\s+is/i.test(trimmed) || /architecture\s+\w+\s+of/i.test(trimmed);
  const isVerilog = /module\s+\w+/i.test(trimmed);
  if (isVhdl && !isVerilog) return parseVhdlHdl(source);
  if (isVerilog && !isVhdl) return parseVerilogHdl(source);
  // If both or ambiguous, try Verilog first, fallback to VHDL
  const vRes = parseVerilogHdl(source);
  if (vRes.doc.nodes.length > 0) return vRes;
  return parseVhdlHdl(source);
}

// Convenience wrappers for bidirectional conversion
export function convertHdlToCircuit(source: string): Doc {
  const res = parseHardwareDescriptionLanguage(source);
  if (res.errors.length && !res.doc.nodes.length) {
    throw new Error(`HDL parse failed: ${res.errors.join("; ")}`);
  }
  return res.doc;
}

export function convertCircuitToHdl(doc: Doc, lang: "verilog" | "vhdl" = "verilog"): string {
  return lang === "vhdl" ? generateVhdl(doc) : generateVerilog(doc);
}

// Keep download helpers
export function downloadTextFile(filename: string, text: string, mime = "text/plain") {
  const blob = new Blob([text], { type: mime });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  URL.revokeObjectURL(a.href);
}

export function downloadJsonFile(filename: string, data: unknown) {
  downloadTextFile(filename, JSON.stringify(data, null, 2), "application/json");
}


