// ---------------------------------------------------------------------------
// Helpers for Verilog emission
// ---------------------------------------------------------------------------

function sanitizeIdentifier(raw: string) {
  let t = raw.replace(/[^A-Za-z0-9_]/g, "_");
  if (!t) t = "n";
  if (/^[0-9]/.test(t)) t = "n_" + t;
  return t;
}

function generateUniqueName(base: string, used: Set<string>) {
  let s = sanitizeIdentifier(base);
  let i = 2;
  while (used.has(s)) s = `${sanitizeIdentifier(base)}_${i++}`;
  used.add(s);
  return s;
}

function getOrCreateNetIdentifier(nodeId: string, port: number, used: Set<string>, cache: Map<string, string>, hint: string) {
  const k = `${nodeId}:${port}`;
  const hit = cache.get(k);
  if (hit) return hit;
  const name = generateUniqueName(hint, used);
  cache.set(k, name);
  return name;
}

// ---------------------------------------------------------------------------
// Emit Verilog (Circuit IR -> HDL)
// Includes a LOGICFORGE IR comment block for lossless round-trip.
// ---------------------------------------------------------------------------

export function generateVerilog(doc: Doc): string {
  const { nodes, wires, defs } = doc;
  const used = new Set<string>(["module", "input", "output", "wire", "assign", "always", "begin", "end", "posedge"]);
  const cache = new Map<string, string>();
  const title = (nId: string) => {
    const n = nodes.find((x) => x.id === nId);
    return n ? nodeTitle(n, defs) : nId;
  };

  const inputs = nodes.filter((n) => n.type === "INPUT" || n.type === "CLOCK");
  const outputs = nodes.filter((n) => n.type === "OUTPUT" || n.type === "LED");

  for (const n of nodes) {
    const sp = specOf(n, defs);
    sp.outs.forEach((nm, i) => getOrCreateNetIdentifier(n.id, i, used, cache, `${title(n.id)}_${nm}`));
    if (n.type === "INPUT" || n.type === "CLOCK") getOrCreateNetIdentifier(n.id, 0, used, cache, title(n.id));
  }

  const inPorts = inputs.map((n) => getOrCreateNetIdentifier(n.id, 0, used, cache, title(n.id)));
  const outPorts = outputs.map((n) => {
    const nm = generateUniqueName(title(n.id) + "_o", used);
    cache.set(`probe:${n.id}`, nm);
    return nm;
  });

  const portList = [...inPorts.map((p) => `  input  ${p}`), ...outPorts.map((p) => `  output ${p}`)].join(",\n");
  const lines: string[] = [];
  const mod = sanitizeIdentifier(doc.name || "LogicForge");
  // IR block for lossless parse: single JSON line per comment
  // Keep it at the very top so the parser can find it quickly.
  try {
    const ir = JSON.stringify(doc);
    lines.push(`// LOGICFORGE_BEGIN`);
    lines.push(`// ${ir}`);
    lines.push(`// LOGICFORGE_END`);
  } catch {
    // ignore
  }
  lines.push(`// Generated by LogicForge`);
  lines.push(`module ${mod} (`);
  lines.push(portList || "  // no ports");
  lines.push(");");
  lines.push("");

  const driven = new Set(inPorts);
  for (const n of nodes) {
    const sp = specOf(n, defs);
    for (let i = 0; i < sp.outs.length; i++) {
      const nm = getOrCreateNetIdentifier(n.id, i, used, cache, `${title(n.id)}_${sp.outs[i]}`);
      if (!driven.has(nm) && !inPorts.includes(nm)) {
        lines.push(`  wire ${nm};`);
        driven.add(nm);
      }
    }
  }
  // For counter regs: declare reg
  for (const n of nodes) {
    if (n.type === "COUNTER") {
      const bits = Math.min(8, Math.max(2, n.bits ?? 4));
      const qn = [...Array(bits)].map((_, i) => getOrCreateNetIdentifier(n.id, i, used, cache, `${title(n.id)}_${specOf(n, defs).outs[i]}`));
      // the internal reg name is separate from output wires
      const regName = generateUniqueName(title(n.id) + "_reg", used);
      // store mapping for later emits: we embed reg name in cache for counter outputs? Not needed.
      // Add manual reg line now, and keep mapping via out net names already declared as wires above.
      // The reg declaration needs to be after wire declarations.
      // We'll push it here and treat out wires already declared.
      lines.push(`  reg [${bits - 1}:0] ${regName};`);
      // Save reg name for per-node use: store in cache under special key
      cache.set(`creg:${n.id}`, regName);
      // Remove regName from driven? It's a reg, not wire.
      void qn;
    }
  }
  lines.push("");

  const srcOf = (node: string, port: number) => {
    const w = wires.find((x) => x.to.node === node && x.to.port === port);
    if (!w) return "1'bx";
    return getOrCreateNetIdentifier(w.from.node, w.from.port, used, cache, title(w.from.node));
  };

  for (const n of nodes) {
    const sp = specOf(n, defs);
    const y = (i = 0) => getOrCreateNetIdentifier(n.id, i, used, cache, `${title(n.id)}_${sp.outs[i] ?? "Y"}`);
    const a = (i: number) => srcOf(n.id, i);
    // Annotate each node's IR for fallback parsers that don't use JSON block
    lines.push(`  // @node ${n.id} type=${n.type} x=${n.x} y=${n.y} ${n.label ? `label=${JSON.stringify(n.label)}` : ""} ${n.bits ? `bits=${n.bits}` : ""} ${n.period ? `period=${n.period}` : ""} ${n.delay != null ? `delay=${n.delay}` : ""}`);
    if (n.type === "INPUT" || n.type === "CLOCK") continue;
    if (n.type === "VCC") { lines.push(`  assign ${y()} = 1'b1;`); continue; }
    if (n.type === "GND") { lines.push(`  assign ${y()} = 1'b0;`); continue; }
    if (n.type === "OUTPUT" || n.type === "LED") {
      const p = cache.get(`probe:${n.id}`);
      if (p) lines.push(`  assign ${p} = ${a(0)};`);
      continue;
    }
    if (isGate(n.type) || n.type === "DELAY") {
      const ins = sp.ins.map((_, i) => a(i));
      const expr =
        n.type === "AND" || n.type === "NAND" ? ins.join(" & ") :
        n.type === "OR" || n.type === "NOR" ? ins.join(" | ") :
        n.type === "XOR" || n.type === "XNOR" ? ins.join(" ^ ") :
        ins[0] ?? "1'bx";
      const wrap = n.type === "NAND" || n.type === "NOR" || n.type === "XNOR" || n.type === "NOT" ? `~(${expr})` : expr;
      lines.push(`  assign ${y()} = ${wrap};`);
      continue;
    }
    if (n.type === "TRI") { lines.push(`  assign ${y()} = ${a(1)} ? ${a(0)} : 1'bz;`); continue; }
    if (n.type === "BUS") { lines.push(`  assign ${y()} = ${sp.ins.map((_, i) => a(i)).join(" | ")};`); continue; }
    if (n.type === "PULLUP") { lines.push(`  assign ${y()} = ${a(0)};`); continue; }
    if (n.type === "PULLDOWN") { lines.push(`  assign ${y()} = ${a(0)};`); continue; }
    if (n.type === "MUX2") { lines.push(`  assign ${y()} = ${a(2)} ? ${a(1)} : ${a(0)};`); continue; }
    if (n.type === "MUX4") {
      lines.push(`  assign ${y()} = ({${a(5)},${a(4)}} == 2'b00) ? ${a(0)} : ({${a(5)},${a(4)}} == 2'b01) ? ${a(1)} : ({${a(5)},${a(4)}} == 2'b10) ? ${a(2)} : ${a(3)};`);
      continue;
    }
    if (n.type === "DEC2") {
      for (let i = 0; i < 4; i++) {
        const aa = i & 1 ? a(0) : `~${a(0)}`;
        const bb = i & 2 ? a(1) : `~${a(1)}`;
        lines.push(`  assign ${y(i)} = ${aa} & ${bb};`);
      }
      continue;
    }
    if (n.type === "ADDER") {
      lines.push(`  assign ${y(0)} = ${a(0)} ^ ${a(1)} ^ ${a(2)};`);
      lines.push(`  assign ${y(1)} = (${a(0)} & ${a(1)}) | (${a(2)} & (${a(0)} ^ ${a(1)}));`);
      continue;
    }
    if (n.type === "DFF") {
      const qReg = y(0);
      lines.push(`  always @(posedge ${a(1)} or posedge ${a(2)}) begin`);
      lines.push(`    if (${a(2)}) ${qReg} <= 1'b0; else ${qReg} <= ${a(0)};`);
      lines.push(`  end`);
      lines.push(`  assign ${y(1)} = ~${qReg};`);
      continue;
    }
    if (n.type === "TFF") {
      const qReg = y(0);
      lines.push(`  always @(posedge ${a(1)} or posedge ${a(2)}) begin`);
      lines.push(`    if (${a(2)}) ${qReg} <= 1'b0; else if (${a(0)}) ${qReg} <= ~${qReg};`);
      lines.push(`  end`);
      lines.push(`  assign ${y(1)} = ~${qReg};`);
      continue;
    }
    if (n.type === "JKFF") {
      const qReg = y(0);
      lines.push(`  always @(posedge ${a(2)} or posedge ${a(3)}) begin`);
      lines.push(`    if (${a(3)}) ${qReg} <= 1'b0;`);
      lines.push(`    else case ({${a(0)}, ${a(1)}})`);
      lines.push(`      2'b10: ${qReg} <= 1'b1; 2'b01: ${qReg} <= 1'b0; 2'b11: ${qReg} <= ~${qReg};`);
      lines.push(`    endcase`);
      lines.push(`  end`);
      lines.push(`  assign ${y(1)} = ~${qReg};`);
      continue;
    }
    if (n.type === "DLATCH") {
      const qReg = y(0);
      lines.push(`  always @(*) if (${a(1)}) ${qReg} = ${a(0)};`);
      lines.push(`  assign ${y(1)} = ~${qReg};`);
      continue;
    }
    if (n.type === "COUNTER") {
      const bits = Math.min(8, Math.max(2, n.bits ?? 4));
      const qn = cache.get(`creg:${n.id}`) ?? generateUniqueName(title(n.id) + "_reg", used);
      // Register was declared earlier; now the sequential logic
      lines.push(`  always @(posedge ${a(0)} or posedge ${a(1)}) begin`);
      lines.push(`    if (${a(1)}) ${qn} <= ${bits}'d0; else ${qn} <= ${qn} + 1'b1;`);
      lines.push(`  end`);
      for (let i = 0; i < bits; i++) lines.push(`  assign ${y(i)} = ${qn}[${i}];`);
      continue;
    }
    if (n.type === "CUSTOM") lines.push(`  // hierarchical ${title(n.id)} ${n.defId ?? ""}`);
  }

  if (nodes.some((n) => isSequential(n.type))) {
    lines.splice(4, 0, "  // Sequential Q ports are driven from always blocks.");
  }

  lines.push("");
  lines.push("endmodule");
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Emit VHDL (Circuit IR -> HDL)
// Generates a synthesizable VHDL entity+architecture and embeds IR block.
// ---------------------------------------------------------------------------

export function generateVhdl(doc: Doc): string {
  const mod = sanitizeIdentifier(doc.name || "LogicForge");
  const ins = doc.nodes.filter((n) => n.type === "INPUT" || n.type === "CLOCK");
  const outs = doc.nodes.filter((n) => n.type === "OUTPUT" || n.type === "LED");
  const ports = [
    ...ins.map((n) => `    ${sanitizeIdentifier(nodeTitle(n, doc.defs))} : in  std_logic`),
    ...outs.map((n) => `    ${sanitizeIdentifier(nodeTitle(n, doc.defs))} : out std_logic`),
  ].join(";\n");

  // Build internal signals for VHDL: mirrors Verilog netIds but as std_logic signals
  // We'll reuse Verilog generation for signal list mapping, but translate to VHDL assignments.
  const v = generateVerilog(doc);
  // For a proper VHDL architecture, translate Verilog assigns to VHDL concurrent assignments.
  // To keep it parseable, we also generate a readable VHDL architecture based on the doc.
  const used = new Set<string>(["entity", "architecture", "signal", "process", "begin", "end", "if", "else", "elsif", "case", "when"]);
  const cache = new Map<string, string>();
  const title = (nId: string) => {
    const n = doc.nodes.find((x) => x.id === nId);
    return n ? nodeTitle(n, doc.defs) : nId;
  };
  for (const n of doc.nodes) {
    const sp = specOf(n, doc.defs);
    sp.outs.forEach((nm, i) => {
      const k = `${n.id}:${i}`;
      if (!cache.has(k)) {
        const sig = sanitizeIdentifier(`${title(n.id)}_${nm}`);
        let base = sig, c = 2;
        while (used.has(base)) base = `${sig}_${c++}`;
        used.add(base);
        cache.set(k, base);
      }
    });
    if (n.type === "INPUT" || n.type === "CLOCK") {
      const k = `${n.id}:0`;
      if (!cache.has(k)) {
        const sig = sanitizeIdentifier(title(n.id));
        let base = sig, c = 2;
        while (used.has(base)) base = `${sig}_${c++}`;
        used.add(base);
        cache.set(k, base);
      }
    }
  }
  const probeMap = new Map<string, string>();
  for (const n of outs) {
    const sig = sanitizeIdentifier(title(n.id) + "_o");
    let base = sig, c = 2;
    while (used.has(base)) base = `${sig}_${c++}`;
    used.add(base);
    probeMap.set(n.id, base);
  }
  const sigId = (nodeId: string, port: number) => cache.get(`${nodeId}:${port}`) ?? sanitizeIdentifier(nodeId);
  const srcOf = (nodeId: string, port: number) => {
    const w = doc.wires.find((x) => x.to.node === nodeId && x.to.port === port);
    if (!w) return "'X'";
    return sigId(w.from.node, w.from.port);
  };

  const vsigs: string[] = [];
  const seenSig = new Set<string>();
  for (const n of doc.nodes) {
    const sp = specOf(n, doc.defs);
    for (let i = 0; i < sp.outs.length; i++) {
      const s = sigId(n.id, i);
      if (!ins.some((x) => sigId(x.id, 0) === s) && !outs.some((x) => probeMap.get(x.id) === s) && !seenSig.has(s)) {
        vsigs.push(`  signal ${s} : std_logic;`);
        seenSig.add(s);
      }
    }
  }
  // Counter regs as vectors
  const vregs: string[] = [];
  for (const n of doc.nodes.filter((x) => x.type === "COUNTER")) {
    const bits = Math.min(8, Math.max(2, n.bits ?? 4));
    const reg = sanitizeIdentifier(title(n.id) + "_reg");
    if (!seenSig.has(reg)) {
      vregs.push(`  signal ${reg} : std_logic_vector(${bits - 1} downto 0);`);
      seenSig.add(reg);
    }
  }

  const lines: string[] = [];
  // IR block for VHDL too (using -- comments)
  try {
    const ir = JSON.stringify(doc);
    lines.push(`-- LOGICFORGE_BEGIN`);
    lines.push(`-- ${ir}`);
    lines.push(`-- LOGICFORGE_END`);
  } catch { /* ignore */ }
  lines.push(`-- Generated by LogicForge`);
  lines.push(`library ieee;`);
  lines.push(`use ieee.std_logic_1164.all;`);
  lines.push(`use ieee.numeric_std.all;`);
  lines.push(``);
  lines.push(`entity ${mod} is`);
  lines.push(`  port (`);
  lines.push(ports || `    -- no ports`);
  lines.push(`  );`);
  lines.push(`end entity;`);
  lines.push(``);
  lines.push(`architecture rtl of ${mod} is`);
  vsigs.forEach((s) => lines.push(s));
  vregs.forEach((s) => lines.push(s));
  lines.push(`begin`);

  for (const n of doc.nodes) {
    const sp = specOf(n, doc.defs);
    const y = (i = 0) => sigId(n.id, i);
    const a = (i: number) => srcOf(n.id, i);
    if (n.type === "INPUT" || n.type === "CLOCK") continue;
    if (n.type === "VCC") { lines.push(`  ${y()} <= '1';`); continue; }
    if (n.type === "GND") { lines.push(`  ${y()} <= '0';`); continue; }
    if (n.type === "OUTPUT" || n.type === "LED") {
      const p = probeMap.get(n.id);
      if (p) lines.push(`  ${p} <= ${a(0)};`);
      continue;
    }
    if (n.type === "AND" || n.type === "OR" || n.type === "XOR") {
      const op = n.type === "AND" ? " and " : n.type === "OR" ? " or " : " xor ";
      const ins = sp.ins.map((_, i) => a(i));
      lines.push(`  ${y()} <= ${ins.join(op)};`);
      continue;
    }
    if (n.type === "NAND" || n.type === "NOR" || n.type === "XNOR" || n.type === "NOT") {
      const baseOp = n.type === "NAND" ? " and " : n.type === "NOR" ? " or " : n.type === "XNOR" ? " xnor " : "";
      if (n.type === "NOT") {
        lines.push(`  ${y()} <= not ${a(0)};`);
      } else {
        const ins = sp.ins.map((_, i) => a(i));
        const inner = ins.join(baseOp === " xnor " ? " xor " : baseOp);
        const wrap = n.type === "XNOR" ? `not (${inner})` : `not (${inner})`;
        // For NAND/NOR, VHDL has nand/nor operators directly
        const op2 = n.type === "NAND" ? " nand " : n.type === "NOR" ? " nor " : " xnor ";
        // Prefer direct
        lines.push(`  ${y()} <= ${ins.join(op2)};`);
        void wrap;
      }
      continue;
    }
    if (n.type === "BUFFER" || n.type === "DELAY") { lines.push(`  ${y()} <= ${a(0)};`); continue; }
    if (n.type === "TRI") { lines.push(`  ${y()} <= ${a(0)} when ${a(1)} = '1' else 'Z';`); continue; }
    if (n.type === "BUS") { lines.push(`  ${y()} <= ${sp.ins.map((_, i) => a(i)).join(" or ")};`); continue; }
    if (n.type === "PULLUP" || n.type === "PULLDOWN") { lines.push(`  ${y()} <= ${a(0)};`); continue; }
    if (n.type === "MUX2") { lines.push(`  ${y()} <= ${a(1)} when ${a(2)} = '1' else ${a(0)};`); continue; }
    if (n.type === "MUX4") {
      lines.push(`  with ${a(4)} & ${a(5)} select`);
      lines.push(`    ${y()} <= ${a(0)} when "00",`);
      lines.push(`             ${a(1)} when "01",`);
      lines.push(`             ${a(2)} when "10",`);
      lines.push(`             ${a(3)} when others;`);
      continue;
    }
    if (n.type === "DEC2") {
      for (let i = 0; i < 4; i++) {
        const aa = i & 1 ? a(0) : `not ${a(0)}`;
        const bb = i & 2 ? a(1) : `not ${a(1)}`;
        lines.push(`  ${y(i)} <= ${aa} and ${bb};`);
      }
      continue;
    }
    if (n.type === "ADDER") {
      lines.push(`  ${y(0)} <= ${a(0)} xor ${a(1)} xor ${a(2)};`);
      lines.push(`  ${y(1)} <= (${a(0)} and ${a(1)}) or (${a(2)} and (${a(0)} xor ${a(1)}));`);
      continue;
    }
    if (n.type === "DFF") {
      const q = y(0);
      lines.push(`  process(${a(1)}, ${a(2)})`);
      lines.push(`  begin`);
      lines.push(`    if ${a(2)} = '1' then`);
      lines.push(`      ${q} <= '0';`);
      lines.push(`    elsif rising_edge(${a(1)}) then`);
      lines.push(`      ${q} <= ${a(0)};`);
      lines.push(`    end if;`);
      lines.push(`  end process;`);
      lines.push(`  ${y(1)} <= not ${q};`);
      continue;
    }
    if (n.type === "TFF") {
      const q = y(0);
      lines.push(`  process(${a(1)}, ${a(2)})`);
      lines.push(`  begin`);
      lines.push(`    if ${a(2)} = '1' then`);
      lines.push(`      ${q} <= '0';`);
      lines.push(`    elsif rising_edge(${a(1)}) then`);
      lines.push(`      if ${a(0)} = '1' then ${q} <= not ${q}; end if;`);
      lines.push(`    end if;`);
      lines.push(`  end process;`);
      lines.push(`  ${y(1)} <= not ${q};`);
      continue;
    }
    if (n.type === "JKFF") {
      const q = y(0);
      lines.push(`  process(${a(2)}, ${a(3)})`);
      lines.push(`  begin`);
      lines.push(`    if ${a(3)} = '1' then`);
      lines.push(`      ${q} <= '0';`);
      lines.push(`    elsif rising_edge(${a(2)}) then`);
      lines.push(`      case ${a(0)} & ${a(1)} is`);
      lines.push(`        when "10" => ${q} <= '1';`);
      lines.push(`        when "01" => ${q} <= '0';`);
      lines.push(`        when "11" => ${q} <= not ${q};`);
      lines.push(`        when others => null;`);
      lines.push(`      end case;`);
      lines.push(`    end if;`);
      lines.push(`  end process;`);
      lines.push(`  ${y(1)} <= not ${q};`);
      continue;
    }
    if (n.type === "DLATCH") {
      const q = y(0);
      lines.push(`  process(${a(1)}, ${a(0)})`);
      lines.push(`  begin`);
      lines.push(`    if ${a(1)} = '1' then ${q} <= ${a(0)}; end if;`);
      lines.push(`  end process;`);
      lines.push(`  ${y(1)} <= not ${q};`);
      continue;
    }
    if (n.type === "COUNTER") {
      const bits = Math.min(8, Math.max(2, n.bits ?? 4));
      const reg = sanitizeIdentifier(title(n.id) + "_reg");
      lines.push(`  process(${a(0)}, ${a(1)})`);
      lines.push(`  begin`);
      lines.push(`    if ${a(1)} = '1' then`);
      lines.push(`      ${reg} <= (others => '0');`);
      lines.push(`    elsif rising_edge(${a(0)}) then`);
      lines.push(`      ${reg} <= std_logic_vector(unsigned(${reg}) + 1);`);
      lines.push(`    end if;`);
      lines.push(`  end process;`);
      for (let i = 0; i < bits; i++) lines.push(`  ${y(i)} <= ${reg}(${i});`);
      continue;
    }
    if (n.type === "CUSTOM") lines.push(`  -- hierarchical ${title(n.id)}`);
  }

  lines.push(`end architecture;`);
  lines.push(``);
  // Append Verilog companion as comment for cross-check (our VHDL parser can also extract it)
  lines.push(`-- ===== Verilog companion =====`);
  v.split("\n").forEach((l) => lines.push(`-- ${l}`));
  lines.push(``);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Parse helpers: IR extraction, comment stripping, etc.
// ---------------------------------------------------------------------------

function tryExtractIR(source: string): Doc | null {
  const beginIdx = source.indexOf("LOGICFORGE_BEGIN");
  const endIdx = source.indexOf("LOGICFORGE_END");
  if (beginIdx === -1 || endIdx === -1 || endIdx <= beginIdx) return null;
  const block = source.slice(beginIdx, endIdx);
  // Split into lines, strip comment prefixes (-- or //)
  const lines = block.split("\n");
  const jsonLines = lines.map((l) => {
    const m = l.match(/^\s*(?:\/\/|--)\s?(.*)$/);
    if (m) return m[1];
    // Also handle line with LOGICFORGE_BEGIN itself
    const m2 = l.match(/LOGICFORGE_BEGIN\s*(.*)/);
    if (m2) return m2[1];
    return l;
  });
  const joined = jsonLines.join("\n");
  const s = joined.indexOf("{");
  const e = joined.lastIndexOf("}");
  if (s === -1 || e === -1 || e <= s) return null;
  const jsonStr = joined.slice(s, e + 1);
  try {
    const doc = JSON.parse(jsonStr);
    if (doc && Array.isArray(doc.nodes) && Array.isArray(doc.wires)) {
      if (!Array.isArray(doc.defs)) doc.defs = [];
      return doc as Doc;
    }
  } catch {
    return null;
  }
  return null;
}

function stripVerilogComments(s: string): string {
  // Remove /* */ first
  let out = s.replace(/\/\*[\s\S]*?\*\//g, "");
  // Remove // lines but keep IR block? IR already extracted, so we can strip all //.
  out = out.replace(/\/\/.*$/gm, "");
  return out;
}

function stripVhdlComments(s: string): string {
  // VHDL comments are -- till end of line
  // But need to keep IR? IR already extracted.
  return s.replace(/--.*$/gm, "");
}

